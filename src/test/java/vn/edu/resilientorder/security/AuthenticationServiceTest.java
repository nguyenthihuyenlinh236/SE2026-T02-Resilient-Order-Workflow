package vn.edu.resilientorder.security;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

public class AuthenticationServiceTest {
    private JdbcTemplate jdbc;
    private AuthenticationService authenticationService;
    private UUID accountId;

    @BeforeEach
    void setUp() {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:auth-" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE ALIAS CLOCK_TIMESTAMP FOR
                "vn.edu.resilientorder.security.AuthenticationServiceTest.clockTimestamp"
                """);
        jdbc.execute("""
                CREATE TABLE accounts (
                    id UUID PRIMARY KEY,
                    username VARCHAR(100) NOT NULL UNIQUE,
                    password_hash VARCHAR(100) NOT NULL,
                    role VARCHAR(20) NOT NULL,
                    store_id VARCHAR(100),
                    enabled BOOLEAN NOT NULL,
                    failed_login_attempts INTEGER NOT NULL,
                    locked_until TIMESTAMP WITH TIME ZONE
                )
                """);
        jdbc.execute("""
                CREATE TABLE security_audit_log (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    actor_account_id UUID,
                    event_type VARCHAR(50),
                    target VARCHAR(500),
                    request_path VARCHAR(500)
                )
                """);

        accountId = UUID.randomUUID();
        jdbc.update(
                """
                INSERT INTO accounts
                    (id, username, password_hash, role, enabled, failed_login_attempts)
                VALUES (?, 'customer', ?, 'CUSTOMER', TRUE, 0)
                """,
                accountId, new BCryptPasswordEncoder(4).encode("correct-password")
        );
        authenticationService = new AuthenticationService(
                jdbc,
                new BCryptPasswordEncoder(4),
                new DataSourceTransactionManager(dataSource),
                5
        );
    }

    @Test
    void locksOnFifthFailureAndResetsAfterLockoutExpires() {
        for (int attempt = 1; attempt <= 4; attempt++) {
            AuthenticationResult result = authenticationService.authenticate(
                    "customer", "wrong-password", "/api/v1/auth/login"
            );
            assertEquals(AuthenticationResult.Failure.INVALID_CREDENTIALS, result.failure());
            assertEquals(attempt, result.failedAttempts());
        }

        AuthenticationResult fifthAttempt = authenticationService.authenticate(
                "customer", "wrong-password", "/api/v1/auth/login"
        );
        assertEquals(AuthenticationResult.Failure.ACCOUNT_LOCKED, fifthAttempt.failure());
        assertEquals(5, fifthAttempt.failedAttempts());

        AuthenticationResult correctPasswordWhileLocked = authenticationService.authenticate(
                "customer", "correct-password", "/api/v1/auth/login"
        );
        assertEquals(AuthenticationResult.Failure.ACCOUNT_LOCKED, correctPasswordWhileLocked.failure());

        jdbc.update(
                "UPDATE accounts SET locked_until = clock_timestamp() - INTERVAL '1' SECOND WHERE id = ?",
                accountId
        );
        AuthenticationResult afterLockout = authenticationService.authenticate(
                "customer", "correct-password", "/api/v1/auth/login"
        );
        assertTrue(afterLockout.isAuthenticated());
        assertEquals(0, jdbc.queryForObject(
                "SELECT failed_login_attempts FROM accounts WHERE id = ?", Integer.class, accountId
        ));
        assertEquals(7, jdbc.queryForObject(
                "SELECT COUNT(*) FROM security_audit_log", Integer.class
        ));
    }

    @Test
    void doesNotRevealWhetherAnAccountExists() {
        AuthenticationResult existing = authenticationService.authenticate(
                "customer", "wrong-password", "/api/v1/auth/login"
        );
        AuthenticationResult missing = authenticationService.authenticate(
                "unknown", "wrong-password", "/api/v1/auth/login"
        );

        assertEquals(existing.failure(), missing.failure());
        assertFalse(missing.isAuthenticated());
    }

    public static Timestamp clockTimestamp() {
        return Timestamp.from(Instant.now());
    }
}

package vn.edu.resilientorder.security;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.mock.web.MockHttpServletRequest;
import org.springframework.mock.web.MockHttpSession;
import org.springframework.transaction.PlatformTransactionManager;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;

public class AccessAuditServiceTest {
    @Test
    void limitsOrderReadsToOwnerOrAssignedStore() {
        AccessAuditService policy = new AccessAuditService(
                mock(JdbcTemplate.class),
                mock(PlatformTransactionManager.class),
                10
        );
        UUID owner = UUID.randomUUID();
        UUID otherUser = UUID.randomUUID();
        AuthenticatedUser customer = new AuthenticatedUser(owner, "customer", AccountRole.CUSTOMER, null);
        AuthenticatedUser staff = new AuthenticatedUser(
                UUID.randomUUID(), "staff", AccountRole.STAFF, "STORE-1"
        );
        AuthenticatedUser admin = new AuthenticatedUser(
                UUID.randomUUID(), "admin", AccountRole.ADMIN, null
        );

        assertTrue(policy.canAccessOrder(customer, owner, "STORE-2"));
        assertFalse(policy.canAccessOrder(customer, otherUser, "STORE-1"));
        assertTrue(policy.canAccessOrder(staff, otherUser, "STORE-1"));
        assertFalse(policy.canAccessOrder(staff, owner, "STORE-2"));
        assertTrue(policy.canAccessOrder(admin, otherUser, "STORE-2"));
    }

    @Test
    void auditsEveryDeniedRequestAndRevokesSessionAtTen() {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:audit-" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE ALIAS CLOCK_TIMESTAMP FOR
                "vn.edu.resilientorder.security.AccessAuditServiceTest.clockTimestamp"
                """);
        jdbc.execute("CREATE TABLE accounts (id UUID PRIMARY KEY)");
        jdbc.execute("""
                CREATE TABLE security_audit_log (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    actor_account_id UUID,
                    event_type VARCHAR(50),
                    target VARCHAR(500),
                    request_path VARCHAR(500),
                    session_id VARCHAR(100),
                    created_at TIMESTAMP WITH TIME ZONE DEFAULT clock_timestamp()
                )
                """);
        jdbc.execute("""
                CREATE TABLE session_denial_counts (
                    session_id VARCHAR(100) PRIMARY KEY,
                    account_id UUID NOT NULL,
                    denied_count INTEGER NOT NULL,
                    updated_at TIMESTAMP WITH TIME ZONE DEFAULT clock_timestamp()
                )
                """);
        jdbc.execute("""
                CREATE TABLE security_alerts (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    account_id UUID NOT NULL,
                    session_id VARCHAR(100) NOT NULL,
                    alert_type VARCHAR(100) NOT NULL,
                    created_at TIMESTAMP WITH TIME ZONE DEFAULT clock_timestamp()
                )
                """);

        UUID accountId = UUID.randomUUID();
        jdbc.update("INSERT INTO accounts (id) VALUES (?)", accountId);
        AccessAuditService service = new AccessAuditService(
                jdbc, new DataSourceTransactionManager(dataSource), 10
        );
        AuthenticatedUser user = new AuthenticatedUser(accountId, "customer", AccountRole.CUSTOMER, null);
        MockHttpSession session = new MockHttpSession();
        String sessionId = session.getId();

        for (int attempt = 0; attempt < 10; attempt++) {
            MockHttpServletRequest request = new MockHttpServletRequest();
            request.setSession(session);
            service.recordDenied(user, request, "another-order", "ORDER_ACCESS_DENIED");
        }

        assertTrue(session.isInvalid());
        assertEquals(10, jdbc.queryForObject(
                "SELECT COUNT(*) FROM security_audit_log", Integer.class
        ));
        assertEquals(10, jdbc.queryForObject(
                "SELECT denied_count FROM session_denial_counts WHERE session_id = ?",
                Integer.class, sessionId
        ));
        assertEquals(1, jdbc.queryForObject(
                "SELECT COUNT(*) FROM security_alerts WHERE alert_type = 'SESSION_REVOKED_AFTER_DENIED_REQUESTS'",
                Integer.class
        ));
    }

    public static Timestamp clockTimestamp() {
        return Timestamp.from(Instant.now());
    }
}
